<?php

declare(strict_types=1);

namespace Sopheak\Core\Types;

use BackedEnum;
use InvalidArgumentException;
use Sopheak\Core\Enums\RecordCastEnum;
use Sopheak\Core\Enums\RecordColumnTypeEnum;
use Sopheak\Core\Mcp\Guidance\ColumnTypes;
use Sopheak\Core\Services\OpenApiService;
use Sopheak\Core\Services\RecordApiResponseService;
use Sopheak\Core\Utilities\DefaultValidationUtils;
use Sopheak\Core\Utilities\SchemaRegistryUtils;

/**
 * Class RecordColumnType.
 *
 * One column of `RecordTableType::$columns`, described with standard,
 * driver-independent parameters. Every parameter maps to something the
 * package acts on:
 *
 * | Parameter       | Effect                                                                 |
 * |-----------------|------------------------------------------------------------------------|
 * | type            | Validation rule, response cast, filter operators, `?search=`, MCP type |
 * | nullable        | `required` vs `nullable` on create                                     |
 * | default         | A column with a database default is not required on create            |
 * | primary         | Primary key: never required on create                                  |
 * | autoIncrement   | Generated by the database: never required on create                    |
 * | enum            | Allowed values: a list, or a backed enum class (`Status::class`)        |
 * | cast            | Response cast override (`integer`, `boolean`, `datetime`, a class, …)  |
 * | compositeType   | PostgreSQL composite type name (`schema.type`) for writes              |
 * | compositeFields | PostgreSQL composite fields (`field => type`)                          |
 * | maxLength       | Maximum length in the MCP payload schemas                              |
 * | nativeType      | The database's own type, kept only when no standard type is exact      |
 * | description     | Column description in OpenAPI and the MCP schema tools                 |
 * | example         | Example value in OpenAPI and the MCP schema tools                      |
 * | meta            | Any other key, passed through unchanged                                |
 *
 * The legacy array form keeps working, and both forms can be mixed in one
 * `columns` list. `RecordTableType` stores every column as the array that
 * {@see self::toArray()} produces, which uses the keys the package already
 * reads (`type`, `nullable`, `default`, `key`, `extra`, …).
 *
 * Example usage:
 * ```php
 * use Sopheak\Core\Enums\RecordColumnTypeEnum as T;
 *
 * columns: [
 *     'id' => new RecordColumnType(type: T::UUID, nullable: false, primary: true),
 *     'status' => new RecordColumnType(type: T::ENUM, nullable: false, default: 'draft', enum: ['draft', 'paid']),
 *     'total' => new RecordColumnType(type: T::DECIMAL, nullable: false, default: 0),
 *     'paid_at' => new RecordColumnType(type: T::DATETIME),
 *     'notes' => ['type' => 'text', 'nullable' => true], // legacy array, still fine
 * ],
 * ```
 */
class RecordColumnType
{
    public RecordColumnTypeEnum $type;

    public ?string $cast = null;

    /**
     * @param RecordColumnTypeEnum|string        $type            A standard type, or a native spelling (`varchar(255)`, `timestamptz`, …) that is cast to one
     * @param array<int, string|int|float>|class-string<BackedEnum>|null $enum A value list, or a backed enum class whose case values are the list
     * @param RecordCastEnum|RecordCastType|string|null $cast     Response cast override
     * @param array<string, string>|null         $compositeFields
     * @param array<string, mixed>               $meta            Any other key of the array form
     */
    public function __construct(
        RecordColumnTypeEnum|string $type,
        public bool $nullable = true,
        public mixed $default = null,
        public bool $primary = false,
        public bool $autoIncrement = false,
        public array|string|null $enum = null,
        RecordCastEnum|RecordCastType|string|null $cast = null,
        public ?string $compositeType = null,
        public ?array $compositeFields = null,
        public ?string $nativeType = null,
        public ?int $maxLength = null,
        public ?string $description = null,
        public mixed $example = null,
        public array $meta = [],
    ) {
        if ($cast instanceof RecordCastEnum) {
            $this->cast = $cast->value;
        } elseif ($cast instanceof RecordCastType) {
            $this->cast = $cast->toCastString();
        } else {
            $this->cast = $cast;
        }

        if (is_string($type)) {
            $standard = RecordColumnTypeEnum::tryFrom(strtolower($type)) ?? RecordColumnTypeEnum::fromNative($type);
            if (null === $standard) {
                if ('' === trim($type)) {
                    throw new InvalidArgumentException('type cannot be empty');
                }

                // Unknown to the package: keep the database spelling so nothing is lost.
                $standard = RecordColumnTypeEnum::STRING;
                $this->nativeType ??= $type;
            }

            $type = $standard;
        }

        $this->type = $type;

        if (is_string($this->enum) && !(enum_exists($this->enum) && is_subclass_of($this->enum, BackedEnum::class))) {
            throw new InvalidArgumentException(sprintf('enum must be a value list or a backed enum class; %s is not a backed enum', $this->enum));
        }

        if (RecordColumnTypeEnum::ENUM === $this->type && [] === $this->enumValues()) {
            throw new InvalidArgumentException('enum values are required when type is ENUM');
        }
    }

    /**
     * The allowed values: the list, or the case values of the enum class.
     *
     * @return array<int, string|int|float>
     */
    public function enumValues(): array
    {
        if (is_string($this->enum)) {
            /** @var class-string<BackedEnum> $class */
            $class = $this->enum;

            return array_map(static fn(BackedEnum $case): string|int => $case->value, $class::cases());
        }

        return array_values($this->enum ?? []);
    }

    /**
     * Build from the array form a config or `getTableColumns()` produces,
     * mapping the driver keys onto the standard parameters.
     *
     * @param array<string, mixed> $definition
     */
    public static function fromArray(array $definition): self
    {
        $meta = $definition;
        $take = static function (string $key) use (&$meta): mixed {
            $value = $meta[$key] ?? null;
            unset($meta[$key]);

            return $value;
        };

        $rawType = (string) ($take('type') ?? '');
        $udtName = $take('udt_name');
        $udtSchema = $take('udt_schema');
        $key = strtoupper((string) ($take('key') ?? ''));
        $extra = (string) ($take('extra') ?? '');
        $default = $take('default');
        $enum = $take('enum');
        $enumClass = $take('enumClass');
        $compositeFields = $take('compositeFields') ?? $take('composite_fields');
        $compositeType = $take('compositeType') ?? $take('composite_type');
        $nullable = $take('nullable');
        $cast = $take('cast');
        $description = $take('description');
        $example = $take('example');
        $maxLength = $take('maxLength');

        $lowerType = strtolower($rawType);
        $isUserDefined = 'user-defined' === $lowerType;
        $hasComposite = is_array($compositeFields) && [] !== $compositeFields;
        $hasEnum = is_array($enum) && [] !== $enum;

        if ($isUserDefined && $hasComposite && null === $compositeType && is_string($udtName) && '' !== $udtName) {
            $compositeType = (is_string($udtSchema) && '' !== $udtSchema && 'public' !== $udtSchema ? $udtSchema . '.' : '') . $udtName;
        }

        // Write a literal default as its PHP value ('0'::numeric -> '0'); keep expressions.
        if (is_string($default)) {
            [$isLiteral, $literal] = SchemaRegistryUtils::literalDefault($default);
            if ($isLiteral && null !== $literal) {
                $default = $literal;
            }
        }

        $autoIncrement = str_contains(strtolower($extra), 'auto_increment') || str_contains(strtolower((string) $default), 'nextval(');
        if (str_contains(strtolower((string) $default), 'nextval(')) {
            $default = null;
        }

        if ('' !== $extra && !str_contains(strtolower($extra), 'auto_increment')) {
            $meta['extra'] = $extra;
        }

        // PostgreSQL reports extension and array types (pgvector, citext,
        // PostGIS, text[]) as USER-DEFINED / ARRAY; the real type is the udt name.
        $standard = match (true) {
            $isUserDefined && $hasEnum => RecordColumnTypeEnum::ENUM,
            $isUserDefined && $hasComposite => null,
            $isUserDefined, 'array' === $lowerType => is_string($udtName) ? RecordColumnTypeEnum::fromNative($udtName) : null,
            default => RecordColumnTypeEnum::fromNative($rawType),
        };

        $column = new self(
            type: $standard ?? RecordColumnTypeEnum::STRING,
            nullable: null === $nullable ? true : (bool) $nullable,
            default: $default,
            primary: 'PRI' === $key,
            autoIncrement: $autoIncrement,
            enum: is_string($enumClass) && enum_exists($enumClass) ? $enumClass : ($hasEnum ? array_values($enum) : null),
            cast: is_string($cast) ? $cast : null,
            compositeType: is_string($compositeType) ? $compositeType : null,
            compositeFields: $hasComposite ? $compositeFields : null,
            nativeType: $standard instanceof RecordColumnTypeEnum ? null : $rawType,
            maxLength: is_numeric($maxLength) ? (int) $maxLength : null,
            description: is_string($description) ? $description : null,
            example: $example,
            meta: $meta,
        );

        // Keep the database spelling (and the udt name it may depend on) when
        // the standard one would make the package validate, cast or filter
        // the column differently.
        if (null === $column->nativeType && self::behaviour($definition) !== self::behaviour($column->toArray())) {
            $column->nativeType = $rawType;
        }

        if (null !== $column->nativeType && ($isUserDefined || 'array' === $lowerType)) {
            $column->meta += array_filter(['udt_name' => $udtName, 'udt_schema' => $udtSchema], static fn(mixed $v): bool => null !== $v);
        }

        return $column;
    }

    /**
     * What the package does with a column definition: its validation rule,
     * response cast, filter family, MCP JSON type, uuid detection and OpenAPI type.
     *
     * @param array<string, mixed> $info
     * @return array<string, mixed>
     */
    private static function behaviour(array $info): array
    {
        $type = (string) ($info['type'] ?? '');

        return [
            DefaultValidationUtils::mapTypeToRule($type, (string) ($info['udt_name'] ?? '')),
            empty($info['compositeFields']) ? RecordApiResponseService::inferBuiltinCastFromColumnMeta($info) : null,
            ColumnTypes::family($type),
            ColumnTypes::jsonSchema($type),
            SchemaRegistryUtils::isUuidColumnType($info),
            OpenApiService::columnTypeSchema(array_diff_key($info, ['enum' => true, 'enumClass' => true])),
        ];
    }

    /**
     * The array form, with the keys the package reads.
     *
     * @return array<string, mixed>
     */
    public function toArray(): array
    {
        $out = [
            'type' => $this->nativeType ?? $this->type->spelling(),
            'nullable' => $this->nullable,
        ];

        if (null !== $this->default) {
            $out['default'] = $this->default;
        }

        if ($this->primary) {
            $out['key'] = 'PRI';
        }

        if ($this->autoIncrement) {
            $out['extra'] = 'auto_increment';
        }

        $optional = [
            'enum' => null === $this->enum ? null : $this->enumValues(),
            // Ignored by the package; lets sync-record-columns keep the class.
            'enumClass' => is_string($this->enum) ? $this->enum : null,
            'cast' => $this->cast,
            'compositeType' => $this->compositeType,
            'compositeFields' => $this->compositeFields,
            'maxLength' => $this->maxLength,
            'description' => $this->description,
            'example' => $this->example,
        ];

        return $out + array_filter($optional, static fn(mixed $value): bool => null !== $value) + $this->meta;
    }

    /**
     * Handle var_export() for configuration caching.
     *
     * @param array<string, mixed> $properties
     */
    public static function __set_state(array $properties): self
    {
        return new self(
            type: $properties['type'],
            nullable: $properties['nullable'] ?? true,
            default: $properties['default'] ?? null,
            primary: $properties['primary'] ?? false,
            autoIncrement: $properties['autoIncrement'] ?? false,
            enum: $properties['enum'] ?? null,
            cast: $properties['cast'] ?? null,
            compositeType: $properties['compositeType'] ?? null,
            compositeFields: $properties['compositeFields'] ?? null,
            nativeType: $properties['nativeType'] ?? null,
            maxLength: $properties['maxLength'] ?? null,
            description: $properties['description'] ?? null,
            example: $properties['example'] ?? null,
            meta: $properties['meta'] ?? [],
        );
    }
}
