<?php

declare(strict_types=1);

namespace Sopheak\Core\Enums;

/**
 * The standard, driver-independent column types of `RecordColumnType`.
 *
 * Covers the types of MySQL / MariaDB, PostgreSQL (including the common
 * extensions: pgvector, PostGIS, citext, hstore) and SQLite, plus the Laravel
 * schema-builder names. `fromNative()` maps any of those spellings to a case.
 *
 * What the package does with each family:
 *
 * | Family    | Cases                                                              | Validation | Cast     | Filters  |
 * |-----------|--------------------------------------------------------------------|------------|----------|----------|
 * | Text      | CHAR, STRING, TEXT, CITEXT                                         | string*    | -        | text     |
 * | Integer   | SMALLINT, INTEGER, BIGINT, YEAR                                    | integer*   | integer  | number   |
 * | Decimal   | DECIMAL, MONEY                                                     | numeric*   | decimal  | number   |
 * | Float     | FLOAT, DOUBLE                                                      | numeric    | float    | number   |
 * | Boolean   | BOOLEAN                                                            | boolean    | boolean  | boolean  |
 * | Temporal  | DATE, DATETIME, TIMESTAMP, TIMESTAMPTZ, TIME, TIMETZ, INTERVAL     | date*      | date(time)* | temporal |
 * | Id        | UUID, ULID                                                         | uuid*      | -        | uuid     |
 * | JSON      | JSON, JSONB                                                        | array      | array    | json     |
 * | Choice    | ENUM, SET                                                          | -          | -        | text     |
 * | Array     | ARRAY                                                              | -          | -        | array    |
 * | Binary    | BINARY, BIT                                                        | -          | -        | other    |
 * | Network   | INET, CIDR, MACADDR                                                | -          | -        | other    |
 * | Geometry  | POINT, LINE, POLYGON, GEOMETRY, GEOGRAPHY                          | -          | -        | other    |
 * | Search    | TSVECTOR, TSQUERY                                                  | -          | -        | other    |
 * | Vector    | VECTOR, HALFVEC, SPARSEVEC (pgvector)                              | -          | -        | other    |
 * | Range     | INT4RANGE, INT8RANGE, NUMRANGE, DATERANGE, TSRANGE, TSTZRANGE      | -          | -        | range    |
 * | Other     | XML, HSTORE                                                        | -          | -        | other    |
 *
 * `*` not for every case of the family — see each case. A column generated by
 * `sp-laravel-api:sync-record-columns` keeps the database spelling in
 * `RecordColumnType::$nativeType` whenever the standard case would change
 * validation, casting or filtering, so generated configs never change behaviour.
 */
enum RecordColumnTypeEnum: string
{
    // Text
    case CHAR = 'char';
    case STRING = 'string';
    case TEXT = 'text';
    case CITEXT = 'citext';

    // Numbers
    case SMALLINT = 'smallint';
    case INTEGER = 'integer';
    case BIGINT = 'bigint';
    case DECIMAL = 'decimal';
    case MONEY = 'money';
    case FLOAT = 'float';
    case DOUBLE = 'double';

    case BOOLEAN = 'boolean';

    // Date and time
    case DATE = 'date';
    case DATETIME = 'datetime';
    case TIMESTAMP = 'timestamp';
    case TIMESTAMPTZ = 'timestamptz';
    case TIME = 'time';
    case TIMETZ = 'timetz';
    case YEAR = 'year';
    case INTERVAL = 'interval';

    // Identifiers
    case UUID = 'uuid';
    case ULID = 'ulid';

    // Structured
    case JSON = 'json';
    case JSONB = 'jsonb';
    case ENUM = 'enum';
    case SET = 'set';
    case ARRAY = 'array';
    case HSTORE = 'hstore';
    case XML = 'xml';

    // Binary
    case BINARY = 'binary';
    case BIT = 'bit';

    // Network (PostgreSQL)
    case INET = 'inet';
    case CIDR = 'cidr';
    case MACADDR = 'macaddr';

    // Geometry (PostgreSQL / PostGIS / MySQL spatial)
    case POINT = 'point';
    case LINE = 'line';
    case POLYGON = 'polygon';
    case GEOMETRY = 'geometry';
    case GEOGRAPHY = 'geography';

    // Full-text search (PostgreSQL)
    case TSVECTOR = 'tsvector';
    case TSQUERY = 'tsquery';

    // Vectors (pgvector)
    case VECTOR = 'vector';
    case HALFVEC = 'halfvec';
    case SPARSEVEC = 'sparsevec';

    // Ranges (PostgreSQL)
    case INT4RANGE = 'int4range';
    case INT8RANGE = 'int8range';
    case NUMRANGE = 'numrange';
    case DATERANGE = 'daterange';
    case TSRANGE = 'tsrange';
    case TSTZRANGE = 'tstzrange';

    /**
     * The `type` string written to the column array. It is the case's own
     * value except `STRING`, written as `varchar` so default validation reads
     * it as a string.
     */
    public function spelling(): string
    {
        return match ($this) {
            self::STRING => 'varchar',
            default => $this->value,
        };
    }

    /**
     * Map a type as a database driver (or a Laravel migration) reports it to
     * a case, or null when it has no equivalent (the caller then keeps the
     * native spelling).
     *
     * Covers MySQL/MariaDB `DESCRIBE`, PostgreSQL `information_schema`
     * (`data_type`, or `udt_name` for USER-DEFINED and ARRAY columns), SQLite
     * `PRAGMA table_info` and Laravel schema-builder names.
     */
    public static function fromNative(string $native): ?self
    {
        $raw = strtolower(trim($native));
        if ('' === $raw) {
            return null;
        }

        if (1 === preg_match('/^tinyint\(\s*1\s*\)/', $raw)) {
            return self::BOOLEAN;
        }

        if (str_starts_with($raw, 'enum(')) {
            return self::ENUM;
        }

        if (str_starts_with($raw, 'set(')) {
            return self::SET;
        }

        // `char(36)` is read as a uuid key by the package but validated as a
        // string; no case keeps both, so it stays native.
        if (1 === preg_match('/^(var)?char\(\s*36\s*\)$/', $raw)) {
            return null;
        }

        if (str_ends_with($raw, '[]') || 'array' === $raw || (str_starts_with($raw, '_') && strlen($raw) > 1)) {
            return self::ARRAY;
        }

        $base = (string) preg_replace('/\(.*?\)/', '', $raw);
        $withTz = str_contains($base, 'with time zone') && !str_contains($base, 'without');
        $base = (string) preg_replace('/\b(unsigned|zerofill|with(out)? time zone)\b/', '', $base);
        $base = (string) preg_replace('/[\s_\-]+/', '', $base);

        return match ($base) {
            'char', 'character', 'bpchar', 'nchar', 'nativecharacter' => self::CHAR,
            'varchar', 'charactervarying', 'varyingcharacter', 'nvarchar', 'string', 'name' => self::STRING,
            'text', 'tinytext', 'mediumtext', 'longtext', 'clob' => self::TEXT,
            'citext' => self::CITEXT,
            'smallint', 'int2', 'tinyint', 'smallserial', 'smallinteger', 'tinyinteger', 'smallincrements', 'tinyincrements' => self::SMALLINT,
            'integer', 'int', 'int4', 'mediumint', 'serial', 'mediuminteger', 'increments', 'mediumincrements' => self::INTEGER,
            'bigint', 'int8', 'bigserial', 'biginteger', 'bigincrements', 'foreignid', 'id' => self::BIGINT,
            'decimal', 'numeric', 'dec', 'fixed' => self::DECIMAL,
            'money', 'smallmoney' => self::MONEY,
            'float', 'float4', 'real' => self::FLOAT,
            'double', 'float8', 'doubleprecision' => self::DOUBLE,
            'bool', 'boolean' => self::BOOLEAN,
            'date' => self::DATE,
            'datetime', 'datetimetz' => self::DATETIME,
            'timestamp' => $withTz ? self::TIMESTAMPTZ : self::TIMESTAMP,
            'timestamptz', 'timestamptztz' => self::TIMESTAMPTZ,
            'time' => $withTz ? self::TIMETZ : self::TIME,
            'timetz' => self::TIMETZ,
            'year' => self::YEAR,
            'interval' => self::INTERVAL,
            'uuid', 'uniqueidentifier' => self::UUID,
            'ulid' => self::ULID,
            'json' => self::JSON,
            'jsonb' => self::JSONB,
            'enum' => self::ENUM,
            'set' => self::SET,
            'hstore' => self::HSTORE,
            'xml' => self::XML,
            'blob', 'tinyblob', 'mediumblob', 'longblob', 'bytea', 'binary', 'varbinary' => self::BINARY,
            'bit', 'varbit', 'bitvarying' => self::BIT,
            'inet', 'inet4', 'inet6', 'ipaddress' => self::INET,
            'cidr' => self::CIDR,
            'macaddr', 'macaddr8', 'macaddress' => self::MACADDR,
            'point' => self::POINT,
            'line', 'lseg', 'linestring', 'multilinestring' => self::LINE,
            'polygon', 'multipolygon', 'box', 'circle', 'path' => self::POLYGON,
            'geometry', 'multipoint', 'geometrycollection', 'geomcollection' => self::GEOMETRY,
            'geography' => self::GEOGRAPHY,
            'tsvector' => self::TSVECTOR,
            'tsquery' => self::TSQUERY,
            'vector' => self::VECTOR,
            'halfvec' => self::HALFVEC,
            'sparsevec' => self::SPARSEVEC,
            'int4range' => self::INT4RANGE,
            'int8range' => self::INT8RANGE,
            'numrange' => self::NUMRANGE,
            'daterange' => self::DATERANGE,
            'tsrange' => self::TSRANGE,
            'tstzrange' => self::TSTZRANGE,
            default => null,
        };
    }
}
